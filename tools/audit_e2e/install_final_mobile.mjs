import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const root=path.resolve(import.meta.dirname,'../..');
const adb='C:/Users/USUARIO/AppData/Local/Android/Sdk/platform-tools/adb.exe';
const serial='emulator-5556';
const run=(...args)=>execFileSync(adb,['-s',serial,...args],{encoding:'utf8',timeout:120000,maxBuffer:2*1024*1024});
const avd=run('emu','avd','name');
if(!avd.includes('EcoRoute_QA'))throw new Error('Refusing installation outside temporary QA AVD');
const apk=path.join(root,'mobile-app/build/app/outputs/flutter-apk/app-x86_64-debug.apk');
const packageName='com.example.ecoroute_driver_app';
const install=run('install','-r','-t',apk);
if(!install.includes('Success'))throw new Error('Installation failed: '+install);
run('shell','am','force-stop',packageName);
const launch=run('shell','monkey','-p',packageName,'-c','android.intent.category.LAUNCHER','1');
const details=run('shell','dumpsys','package',packageName).split('\n').filter(line=>/versionCode=|versionName=|firstInstallTime=|lastUpdateTime=/.test(line));
const result={at:new Date().toISOString(),serial,avd:avd.trim(),apk:path.relative(root,apk),bytes:fs.statSync(apk).size,sha256:createHash('sha256').update(fs.readFileSync(apk)).digest('hex'),install:install.trim(),launchSucceeded:launch.includes('Events injected: 1'),package:packageName,details,preservedAppData:true,originalEmulatorsModified:false,humanAcceptance:'PENDING'};
fs.writeFileSync(path.join(root,'docs/correccion_integral/evidencias/instalacion_mobile_final.json'),JSON.stringify(result,null,2));
console.log(JSON.stringify(result));
